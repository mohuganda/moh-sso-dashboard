/* global process */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize } from "node:path";
import { fileURLToPath } from "node:url";

const [, , kind, name] = process.argv;

if (!kind || !name || !["app", "package"].includes(kind)) {
  throw new Error("Usage: node scripts/write-package-declarations.mjs <app|package> <name>");
}

const frontendRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const baseDir = kind === "app" ? join(frontendRoot, "apps", name) : join(frontendRoot, "packages", name);
const srcDir = join(baseDir, "src");
const distDir = join(baseDir, "dist");

mkdirSync(distDir, { recursive: true });

function readSource(path) {
  return existsSync(path) ? readFileSync(path, "utf8") : "";
}

function sourcePath(relativePath) {
  for (const extension of [".ts", ".tsx"]) {
    const candidate = join(srcDir, `${relativePath}${extension}`);
    if (existsSync(candidate)) {
      return candidate;
    }
  }

  const indexCandidate = join(srcDir, relativePath, "index.ts");
  return existsSync(indexCandidate) ? indexCandidate : null;
}

function publicName(namePart) {
  const cleaned = namePart.replace(/^type\s+/, "").trim();
  const [local, alias] = cleaned.split(/\s+as\s+/).map((part) => part.trim());
  return alias ?? local;
}

function isTypeExport(namePart) {
  return namePart.trim().startsWith("type ");
}

function collectExports(file, visited = new Set()) {
  const normalized = normalize(file);

  if (visited.has(normalized)) {
    return { values: new Set(), types: new Set() };
  }

  visited.add(normalized);

  const source = readSource(file);
  const values = new Set();
  const types = new Set();

  for (const match of source.matchAll(/export\s+\*\s+from\s+["'](.+)["']/g)) {
    const target = sourcePath(match[1]);
    if (!target) {
      continue;
    }

    const nested = collectExports(target, visited);
    nested.values.forEach((value) => values.add(value));
    nested.types.forEach((type) => types.add(type));
  }

  for (const match of source.matchAll(/export\s+type\s+\{([^}]+)\}/g)) {
    match[1]
      .split(",")
      .map((part) => publicName(part.trim()))
      .filter(Boolean)
      .forEach((type) => types.add(type));
  }

  for (const match of source.matchAll(/export\s+\{([^}]+)\}/g)) {
    for (const part of match[1].split(",")) {
      const name = publicName(part.trim());
      if (!name) {
        continue;
      }

      if (isTypeExport(part)) {
        types.add(name);
      } else {
        values.add(name);
      }
    }
  }

  for (const match of source.matchAll(/export\s+(?:declare\s+)?(?:const|let|var|function|class|enum)\s+([A-Za-z_$][\w$]*)/g)) {
    values.add(match[1]);
  }

  for (const match of source.matchAll(/export\s+(?:declare\s+)?(?:type|interface)\s+([A-Za-z_$][\w$]*)/g)) {
    types.add(match[1]);
  }

  for (const match of source.matchAll(/export\s+default\s+(?:function|class)?\s*([A-Za-z_$][\w$]*)?/g)) {
    values.add("default");
    if (match[1]) {
      values.add(match[1]);
    }
  }

  return { values, types };
}

function declarationForExports(entryPath) {
  const { values, types } = collectExports(entryPath);
  const lines = [
    "// Generated by scripts/write-package-declarations.mjs.",
    "// Public declarations are intentionally npm-safe and do not reference src/.",
  ];

  if (values.has("default")) {
    lines.push("declare const _default: any;", "export default _default;");
    values.delete("default");
  }

  for (const name of [...types].sort()) {
    lines.push(`export type ${name} = any;`);
  }

  for (const name of [...values].sort()) {
    lines.push(`export const ${name}: any;`);
  }

  if (lines.length === 2) {
    lines.push("export {};");
  }

  return `${lines.join("\n")}\n`;
}

function writeDeclaration(entryName) {
  const entryPath = sourcePath(entryName);
  const outputPath = join(distDir, `${entryName}.d.ts`);

  if (!entryPath) {
    writeFileSync(outputPath, "export {};\n");
    return;
  }

  writeFileSync(outputPath, declarationForExports(entryPath));
}

if (kind === "app") {
  writeDeclaration("index");
  writeDeclaration("routes");
  writeDeclaration("api");
  writeDeclaration("types");
  writeFileSync(
    join(distDir, "single-spa.d.ts"),
    [
      "// Generated by scripts/write-package-declarations.mjs.",
      'import type { MicrofrontendLifecycle } from "@moh-sso/microfrontend";',
      'export const bootstrap: MicrofrontendLifecycle["bootstrap"];',
      'export const mount: MicrofrontendLifecycle["mount"];',
      'export const unmount: MicrofrontendLifecycle["unmount"];',
      "",
    ].join("\n"),
  );
} else {
  writeDeclaration("index");
}
